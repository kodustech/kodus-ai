#!/usr/bin/env node
// The Kody Runtime's module docs (docs/runtime/module-docs.md): every module of
// the Runtime is a directory with source files, and each has an AGENTS.md that
// says what it is for. This script keeps the part of each AGENTS.md that the
// code can say: the block between the module-map markers, with the module's
// files and which Runtime modules it imports and is imported by.
//
//   node scripts/runtime/module-docs.mjs --check   # exit 1 naming each module whose doc is missing or stale
//   node scripts/runtime/module-docs.mjs --write   # rewrite every block (a module without AGENTS.md is reported, not created)
//   node scripts/runtime/module-docs.mjs --list    # the modules, one per line
//
// No dependencies: imports are read with a regex, aliases from tsconfig.json's
// "@libs/*" and "@apps/*", Go imports by the cell's module path.
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const GO_MODULE = 'github.com/kodustech/kodus-ai/apps/runtime-cell';

// Where the Runtime's modules live. A module is a directory under one of these
// that holds at least one source file that is not a test.
export const SCOPES = [
    { root: 'apps/runtime/src', lang: 'ts' },
    { root: 'libs/runtime', lang: 'ts' },
    { root: 'libs/runtime-publish', lang: 'ts' },
    { root: 'apps/runtime-cell/internal', lang: 'go' },
    { root: 'apps/runtime-cell/cmd', lang: 'go' },
];

const SKIP_DIRS = new Set(['node_modules', '__tests__', 'fixtures', 'testdata', 'dist', '.git']);
const START = '<!-- module-map:start (generated by scripts/runtime/module-docs.mjs; do not edit) -->';
const END = '<!-- module-map:end -->';

const isTest = (f, lang) => (lang === 'go' ? f.endsWith('_test.go') : /\.(spec|test)\.ts$/.test(f) || f.endsWith('.d.ts'));
const isSource = (f, lang) => (lang === 'go' ? f.endsWith('.go') : f.endsWith('.ts')) && !isTest(f, lang);

function walk(dir, lang, out) {
    let entries;
    try {
        entries = readdirSync(join(ROOT, dir), { withFileTypes: true });
    } catch {
        return;
    }
    const files = entries.filter((e) => e.isFile() && isSource(e.name, lang)).map((e) => e.name).sort();
    if (files.length > 0) out.push({ dir, lang, files });
    for (const e of entries) {
        if (e.isDirectory() && !SKIP_DIRS.has(e.name) && !e.name.startsWith('.')) walk(join(dir, e.name), lang, out);
    }
}

export function modules() {
    const out = [];
    for (const s of SCOPES) walk(s.root, s.lang, out);
    return out.sort((a, b) => a.dir.localeCompare(b.dir));
}

// The module a source path belongs to: the deepest module directory holding it.
function moduleOf(path, dirs) {
    let d = dirname(path);
    while (d && d !== '.' && d !== sep) {
        if (dirs.has(d)) return d;
        d = dirname(d);
    }
    return null;
}

function tsTargets(file, src) {
    const out = [];
    const re = /(?:import|export)\s+(?:type\s+)?(?:[^'";]*?\sfrom\s+)?['"]([^'"]+)['"]|import\(\s*['"]([^'"]+)['"]\s*\)|require\(\s*['"]([^'"]+)['"]\s*\)/g;
    for (const m of src.matchAll(re)) {
        const spec = m[1] || m[2] || m[3];
        let p = null;
        if (spec.startsWith('.')) p = join(dirname(file), spec);
        else if (spec.startsWith('@libs/')) p = join('libs', spec.slice('@libs/'.length));
        else if (spec.startsWith('@apps/')) {
            const [app, ...rest] = spec.slice('@apps/'.length).split('/');
            p = join('apps', app, 'src', ...rest);
        }
        if (p) out.push(p);
    }
    return out;
}

function goTargets(src) {
    const out = [];
    const block = src.match(/^import\s*\(([\s\S]*?)^\)/m);
    const lines = block ? block[1].split('\n') : [];
    for (const m of src.matchAll(/^import\s+(?:\w+\s+)?"([^"]+)"/gm)) lines.push(`"${m[1]}"`);
    for (const l of lines) {
        const m = l.match(/"([^"]+)"/);
        if (m && m[1].startsWith(GO_MODULE + '/')) out.push(join('apps/runtime-cell', m[1].slice(GO_MODULE.length + 1)));
    }
    return out;
}

// Resolve a TS target (a file without extension, or a directory with an
// index) to the module that holds it.
function resolveModule(target, dirs) {
    for (const cand of [target, `${target}.ts`, join(target, 'index.ts')]) {
        if (existsSync(join(ROOT, cand))) {
            const isDir = statSync(join(ROOT, cand)).isDirectory();
            if (isDir && dirs.has(cand)) return cand;
            return moduleOf(isDir ? join(cand, 'x') : cand, dirs);
        }
    }
    return moduleOf(`${target}.ts`, dirs);
}

export function graph() {
    const mods = modules();
    const dirs = new Set(mods.map((m) => m.dir));
    const imports = new Map(mods.map((m) => [m.dir, new Set()]));
    const importedBy = new Map(mods.map((m) => [m.dir, new Set()]));
    for (const m of mods) {
        for (const f of m.files) {
            const path = join(m.dir, f);
            const src = readFileSync(join(ROOT, path), 'utf8');
            const targets = m.lang === 'go' ? goTargets(src) : tsTargets(path, src);
            for (const t of targets) {
                const to = m.lang === 'go' ? (dirs.has(t) ? t : null) : resolveModule(t, dirs);
                if (to && to !== m.dir) {
                    imports.get(m.dir).add(to);
                    importedBy.get(to).add(m.dir);
                }
            }
        }
    }
    return { mods, imports, importedBy };
}

const link = (from, to) => `[\`${to}\`](${relative(from, to).split(sep).join('/')}/AGENTS.md)`;

export function block(m, g) {
    const list = (set) => {
        const xs = [...set].sort();
        return xs.length ? xs.map((d) => `- ${link(m.dir, d)}`).join('\n') : '- none';
    };
    const files = m.files.length > 40 ? [...m.files.slice(0, 40), `… and ${m.files.length - 40} more`] : m.files;
    return [
        START,
        '',
        '## Module map',
        '',
        `Files (${m.files.length}, tests apart): ${files.map((f) => (f.startsWith('…') ? f : `\`${f}\``)).join(', ')}`,
        '',
        'Imports these Runtime modules:',
        '',
        list(g.imports.get(m.dir)),
        '',
        'Imported by:',
        '',
        list(g.importedBy.get(m.dir)),
        '',
        END,
    ].join('\n');
}

function withBlock(doc, b) {
    const i = doc.indexOf(START.slice(0, 30));
    const j = doc.indexOf(END);
    if (i >= 0 && j > i) return doc.slice(0, i) + b + doc.slice(j + END.length);
    return doc.replace(/\s*$/, '') + '\n\n' + b + '\n';
}

function main(argv) {
    const mode = argv[2] || '--check';
    const g = graph();
    if (mode === '--list') {
        for (const m of g.mods) console.log(m.dir);
        return 0;
    }
    const problems = [];
    for (const m of g.mods) {
        const p = join(ROOT, m.dir, 'AGENTS.md');
        if (!existsSync(p)) {
            problems.push(`${m.dir}: no AGENTS.md`);
            continue;
        }
        const doc = readFileSync(p, 'utf8');
        const next = withBlock(doc, block(m, g));
        if (next !== doc) {
            if (mode === '--write') writeFileSync(p, next);
            else problems.push(`${m.dir}: the module map is stale (node scripts/runtime/module-docs.mjs --write)`);
        }
    }
    for (const line of problems) console.error(line);
    if (problems.length) console.error(`${problems.length} of ${g.mods.length} modules need their AGENTS.md (docs/runtime/module-docs.md)`);
    return problems.length && mode === '--check' ? 1 : 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exitCode = main(process.argv);
