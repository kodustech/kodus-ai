import { Test, TestingModule } from '@nestjs/testing';
import { CommentManagerService } from '@libs/code-review/infrastructure/adapters/services/commentManager.service';
import { PULL_REQUESTS_SERVICE_TOKEN } from '@libs/platformData/domain/pullRequests/contracts/pullRequests.service.contracts';
import { PARAMETERS_SERVICE_TOKEN } from '@libs/organization/domain/parameters/contracts/parameters.service.contract';
import { MessageTemplateProcessor } from '@libs/code-review/infrastructure/adapters/services/messageTemplateProcessor.service';
import { ObservabilityService } from '@libs/core/log/observability.service';
import { setLlmObservability } from '@libs/llm/llm-observability';
import { PermissionValidationService } from '@libs/ee/shared/services/permissionValidation.service';
import { CodeManagementService } from '@libs/platform/infrastructure/adapters/services/codeManagement.service';
import { FileChange } from '@libs/core/infrastructure/config/types/general/codeReview.type';
import { BehaviourForNewCommits } from '@libs/core/domain/enums/code-review.enum';

jest.mock('@libs/core/log/logger', () => ({
    createLogger: () => ({
        log: jest.fn(),
        error: jest.fn(),
        warn: jest.fn(),
        debug: jest.fn(),
        info: jest.fn(),
    }),
}));

const LLM_SUMMARY = 'New summary generated by LLM.';

function makeFile(filename: string): Partial<FileChange> {
    return {
        filename,
        patch: `${filename}_${'x'.repeat(200)}`,
        status: 'modified',
    } as Partial<FileChange>;
}

/**
 * Replacing the description used to drop the author's issue link along with
 * it, which unlinks the issue on the provider and leaves later business-logic
 * runs with no task to resolve.
 */
describe('CommentManagerService – task references survive a replaced description', () => {
    let service: CommentManagerService;
    let mockCodeManagementService: any;

    const organizationAndTeamData = {
        organizationId: 'org-123',
        teamId: 'team-456',
    };
    const repository = { id: 'repo-1', name: 'test-repo' };
    const pullRequest = {
        number: 42,
        title: 'Test PR',
        head: { ref: 'feature-branch', repo: { fullName: 'org/repo' } },
        base: { ref: 'main' },
    };

    const generate = (summaryConfig: Record<string, unknown>) =>
        service.generateSummaryPR(
            pullRequest,
            repository,
            [makeFile('a.ts')],
            organizationAndTeamData as any,
            'en-US',
            summaryConfig as any,
            undefined,
            false, // first review, not a commit run
        );

    beforeEach(async () => {
        const observability = {
            runAiSdkLLMInSpan: jest
                .fn()
                .mockImplementation(async () => ({ text: LLM_SUMMARY })),
        };
        setLlmObservability(observability as any);

        mockCodeManagementService = { getPullRequestByNumber: jest.fn() };

        const module: TestingModule = await Test.createTestingModule({
            providers: [
                CommentManagerService,
                { provide: PULL_REQUESTS_SERVICE_TOKEN, useValue: {} },
                { provide: PARAMETERS_SERVICE_TOKEN, useValue: {} },
                { provide: MessageTemplateProcessor, useValue: {} },
                { provide: ObservabilityService, useValue: observability },
                {
                    provide: PermissionValidationService,
                    useValue: {
                        validateBasicLicense: jest
                            .fn()
                            .mockResolvedValue({ allowed: true }),
                        getBYOKConfig: jest.fn().mockResolvedValue(null),
                    },
                },
                {
                    provide: CodeManagementService,
                    useValue: mockCodeManagementService,
                },
            ],
        }).compile();

        service = module.get<CommentManagerService>(CommentManagerService);
    });

    it('keeps the closing keyword when the description is replaced', async () => {
        mockCodeManagementService.getPullRequestByNumber.mockResolvedValue({
            body: 'Closes #993\n\nAdds a per-second rate limiter.',
        });

        const result = await generate({
            generatePRSummary: true,
            behaviourForExistingDescription: 'replace',
            behaviourForNewCommits: BehaviourForNewCommits.NONE,
        });

        expect(result).toContain('Closes #993');
        expect(result).toContain(LLM_SUMMARY);
        // The prose is still replaced — only the reference is carried over.
        expect(result).not.toContain('Adds a per-second rate limiter.');
    });

    it("keeps an id in the team's own format when the description is replaced", async () => {
        mockCodeManagementService.getPullRequestByNumber.mockResolvedValue({
            body: 'Story T1234\n\nSome prose.',
        });
        const summaryConfig = {
            generatePRSummary: true,
            behaviourForExistingDescription: 'replace',
            behaviourForNewCommits: BehaviourForNewCommits.NONE,
        };

        const withPattern = await service.generateSummaryPR(
            pullRequest,
            repository,
            [makeFile('a.ts')],
            organizationAndTeamData as any,
            'en-US',
            summaryConfig as any,
            undefined,
            false,
            undefined,
            undefined,
            undefined,
            undefined,
            'T(\\d{4})',
        );
        expect(withPattern).toContain('Story T1234');

        // Without the team's pattern no built-in shape reads it.
        expect(await generate(summaryConfig)).not.toContain('T1234');
    });

    it('keeps a jira-style key when the description is replaced', async () => {
        mockCodeManagementService.getPullRequestByNumber.mockResolvedValue({
            body: 'Implements PROJ-42\n\nSome prose.',
        });

        const result = await generate({
            generatePRSummary: true,
            behaviourForExistingDescription: 'replace',
            behaviourForNewCommits: BehaviourForNewCommits.NONE,
        });

        expect(result).toContain('PROJ-42');
    });

    it.each([
        ['an Azure Boards work item', 'Closes AB#12'],
        [
            'an Azure Boards link',
            'Implements https://dev.azure.com/acme/web/_workitems/edit/12',
        ],
    ])('keeps %s when the description is replaced', async (_kind, line) => {
        mockCodeManagementService.getPullRequestByNumber.mockResolvedValue({
            body: `${line}\n\nSome prose.`,
        });

        const result = await generate({
            generatePRSummary: true,
            behaviourForExistingDescription: 'replace',
            behaviourForNewCommits: BehaviourForNewCommits.NONE,
        });

        expect(result).toContain(line);
        expect(result).not.toContain('Some prose.');
    });

    it('replaces a description that carries no reference, as before', async () => {
        mockCodeManagementService.getPullRequestByNumber.mockResolvedValue({
            body: 'Just some prose with no task link.',
        });

        const result = await generate({
            generatePRSummary: true,
            behaviourForExistingDescription: 'replace',
            behaviourForNewCommits: BehaviourForNewCommits.NONE,
        });

        expect(result).not.toContain('Just some prose');
        expect(result).toContain(LLM_SUMMARY);
    });

    it('does not duplicate the reference when the description is concatenated', async () => {
        mockCodeManagementService.getPullRequestByNumber.mockResolvedValue({
            body: 'Closes #993\n\nAdds a per-second rate limiter.',
        });

        const result = await generate({
            generatePRSummary: true,
            behaviourForExistingDescription: 'concatenate',
            behaviourForNewCommits: BehaviourForNewCommits.NONE,
        });

        expect(result.match(/Closes #993/g)).toHaveLength(1);
        expect(result).toContain('Adds a per-second rate limiter.');
    });
});
