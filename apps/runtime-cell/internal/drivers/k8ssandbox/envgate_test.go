var updateManifest = flag.Bool("update-manifest", false, "rewrite deploy/kubernetes/environment-namespace.yaml")

// manifestFile is the reference copy the installer's chart carries.
var manifestFile = filepath.Join("..", "..", "..", "deploy", "kubernetes", "environment-namespace.yaml")

// ManifestYAML is the objects as one multi-document YAML file.
func manifestYAML(t *testing.T, objs []Object) []byte {
	t.Helper()
	var b bytes.Buffer
	b.WriteString("# Generated by internal/drivers/k8ssandbox EnvironmentNamespace (go test -run TestTheEnvironmentNamespaceManifest -update-manifest).\n")
	b.WriteString("# The environment namespace of one cell: Pod Security privileged, the gate, default deny, the cell's and the reaper's Roles and bindings.\n")
	for _, o := range objs {
		out, err := yaml.Marshal(o)
		if err != nil {
			t.Fatal(err)
		}
		b.WriteString("---\n")
		b.Write(out)
	}
	return b.Bytes()
}

// The environment namespace runs at Pod Security privileged, so the gate is
// the ValidatingAdmissionPolicy: bound to that namespace only, failing
// closed, on every pod create and update (ephemeral containers too), with
// one rule per thing the design forbids.
func TestTheEnvironmentNamespaceManifest(t *testing.T) {
	objs, err := EnvironmentNamespace("kodus-runtime-environments", []string{"gvisor"}, ReferenceEnvAccess)
	if err != nil {
		t.Fatal(err)
	}
	kinds := map[string]Object{}
	for _, o := range objs {
		kinds[o["kind"].(string)] = o
	}
	ns := meta(kinds["Namespace"])["labels"].(map[string]any)
	if ns["pod-security.kubernetes.io/enforce"] != "privileged" || ns["pod-security.kubernetes.io/warn"] != "baseline" {
		t.Errorf("namespace labels %v", ns)
	}
	vap := kinds["ValidatingAdmissionPolicy"]["spec"].(map[string]any)
	if vap["failurePolicy"] != "Fail" {
		t.Error("the gate must fail closed")
	}
	rules := vap["matchConstraints"].(map[string]any)["resourceRules"].([]any)[0].(map[string]any)
	if strings.Join(asStrings(rules["resources"]), ",") != "pods,pods/ephemeralcontainers" || strings.Join(asStrings(rules["operations"]), ",") != "CREATE,UPDATE" {
		t.Errorf("rules %v", rules)
	}
	var exprs []string
	for _, v := range vap["validations"].([]any) {
		exprs = append(exprs, v.(map[string]any)["expression"].(string))
	}
	all := strings.Join(exprs, "\n")
	for _, want := range []string{"runtimeClassName in ['gvisor']", "!has(v.hostPath)", "hostNetwork", "hostPID", "hostIPC", "hostPort",
		"automountServiceAccountToken == false", "serviceAccountToken", "startsWith('kata')", "c.securityContext.privileged == false",
		"initContainers", "ephemeralContainers",
		"seccompProfile.type in ['RuntimeDefault', 'Localhost']", "appArmorProfile.type == 'Unconfined'", "c.name == 'buildkitd'", "runAsNonRoot == true",
		"capabilities.add", "procMount", "container.apparmor.security.beta.kubernetes.io/"} {
		if !strings.Contains(all, want) {
			t.Errorf("no rule reads %q", want)
		}
	}
	bind := kinds["ValidatingAdmissionPolicyBinding"]["spec"].(map[string]any)
	sel := bind["matchResources"].(map[string]any)["namespaceSelector"].(map[string]any)["matchLabels"].(map[string]any)
	if bind["policyName"] != EnvGatePolicy || sel["kubernetes.io/metadata.name"] != "kodus-runtime-environments" || asStrings(bind["validationActions"])[0] != "Deny" {
		t.Errorf("binding %v", bind)
	}
	deny := kinds["NetworkPolicy"]["spec"].(map[string]any)
	if len(deny["podSelector"].(map[string]any)) != 0 || len(deny["policyTypes"].([]any)) != 2 {
		t.Errorf("default deny %v", deny)
	}
	roles := map[string]string{}
	for _, o := range objs {
		md := meta(o)
		switch o["kind"] {
		case "Role":
			roles[str(md["name"])] = jsonOf(o["rules"])
		case "RoleBinding":
			subj := o["subjects"].([]any)[0].(map[string]any)
			roles[str(md["name"])+" bound to"] = str(subj["namespace"]) + "/" + str(subj["name"])
			if o["roleRef"].(map[string]any)["name"] != md["name"] {
				t.Errorf("binding %v", o)
			}
		}
	}
	wantRoles := map[string]string{
		"kodus-runtime-cell-environments": `[{"apiGroups":[""],"resources":["pods"],"verbs":["create","get","list","delete","patch"]},` +
			`{"apiGroups":[""],"resources":["pods/exec"],"verbs":["create","get"]},{"apiGroups":[""],"resources":["pods/log"],"verbs":["get"]},` +
			`{"apiGroups":[""],"resources":["persistentvolumeclaims"],"verbs":["create","list","delete"]},` +
			`{"apiGroups":["networking.k8s.io"],"resources":["networkpolicies"],"verbs":["create","list","delete"]}]`,
		"kodus-runtime-cell-environments bound to": "kodus-runtime/kodus-runtime-cell",
		"kodus-runtime-reaper-environments": `[{"apiGroups":[""],"resources":["pods"],"verbs":["get","list","delete"]},` +
			`{"apiGroups":[""],"resources":["persistentvolumeclaims"],"verbs":["list","delete"]},` +
			`{"apiGroups":["networking.k8s.io"],"resources":["networkpolicies"],"verbs":["list","delete"]}]`,
		"kodus-runtime-reaper-environments bound to": "kodus-runtime/kodus-runtime-reaper",
	}
	for k, v := range wantRoles {
		if roles[k] != v {
			t.Errorf("%s:\n got %s\nwant %s", k, roles[k], v)
		}
	}
	if len(roles) != len(wantRoles) {
		t.Errorf("roles %v", roles)
	}
	got := manifestYAML(t, objs)
	if *updateManifest {
		if err := os.MkdirAll(filepath.Dir(manifestFile), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(manifestFile, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(manifestFile)
	if err != nil || !bytes.Equal(got, want) {
		t.Errorf("%s is not the render (run with -update-manifest): %v", manifestFile, err)
	}
}

func TestTheGateRefusesNamesItCannotQuote(t *testing.T) {
	for _, c := range [][]string{nil, {"gvisor'] || true || ['"}, {"Upper"}} {
		if _, err := EnvironmentNamespace("ns", c, ReferenceEnvAccess); err == nil {
			t.Errorf("classes %q accepted", c)
		}
	}
	if _, err := EnvironmentNamespace("bad.ns", []string{"gvisor"}, ReferenceEnvAccess); err == nil {
		t.Error("a dotted namespace accepted")
	}
}

func asStrings(v any) []string {
	var out []string
	for _, e := range v.([]any) {
		out = append(out, e.(string))
	}
	return out
}
